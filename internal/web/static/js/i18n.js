export const DICT = { vi: VI, en: EN, zh: ZH, fr: FR, ja: JA, ko: KO, es: ES, pt: PT, de: DE, it: IT, ru: RU };

export function detectInitialLang() {
  try {
    const saved = localStorage.getItem('ibmon-lang');
    if (saved && DICT[saved]) return saved;
  } catch {}
  const nav = (navigator.language || 'vi').toLowerCase().split('-')[0];
  return DICT[nav] ? nav : 'vi';
}

export function tr(lang, key, vars = {}) {
  const pack = DICT[lang] || DICT.vi;
  let s = pack[key] || DICT.en[key] || key;
  for (const [k, v] of Object.entries(vars)) {
    s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}
